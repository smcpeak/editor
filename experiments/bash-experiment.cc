// bash-experiment.cc
// Invoke bash the way claude.exe does, to try to repro a bash crash.

// See bash-experiment.txt for the specification and bash-crash.txt
// for the background.
//
// Build (MinGW, so it is a native program like claude.exe):
//
//   g++ -Wall -o bash-experiment.exe bash-experiment.cc
//
// Usage:
//
//   bash-experiment.exe <bash> <size>
//
// where <size> is the size in bytes of the heredoc body, including
// its final newline (the measure used in bash-crash.txt).
//
// Beyond the specification, the details of process creation follow
// what libuv's `uv_spawn` does on Windows, on the assumption that
// claude.exe uses it: the CRT stdio handle table in `lpReserved2`,
// `STARTF_USESHOWWINDOW`, `CREATE_UNICODE_ENVIRONMENT`, inherited
// handles, and a kill-on-close job object.  The bash arguments and
// wrapper text are copied from a `ps` listing of a bash process that
// the Bash tool started.

#include <windows.h>                   // Win32 API

#include <stdio.h>                     // printf, fprintf, fwrite
#include <stdlib.h>                    // strtol
#include <string.h>                    // memcpy

#include <string>                      // std::string, std::wstring
#include <thread>                      // std::thread
#include <vector>                      // std::vector


// Exit codes.
enum {
  EXIT_BASH_OK = 0,
  EXIT_BASH_FAILED = 1,
  EXIT_ERROR = 2,
};


// Print `GetLastError()` for a failed call to `func`, and exit.
static void failWin32(char const *func)
{
  DWORD code = GetLastError();
  char buf[512] = "";
  FormatMessageA(
    FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS,
    nullptr, code, 0, buf, sizeof(buf), nullptr);
  fprintf(stderr, "bash-experiment: %s failed: code %lu: %s\n",
    func, (unsigned long)code, buf);
  exit(EXIT_ERROR);
}


// Convert UTF-8 `s` to UTF-16.
static std::wstring toWide(std::string const &s)
{
  if (s.empty()) {
    return std::wstring();
  }
  int len = MultiByteToWideChar(CP_UTF8, 0, s.data(), (int)s.size(),
                                nullptr, 0);
  if (len == 0) {
    failWin32("MultiByteToWideChar");
  }
  std::wstring ret(len, L'\0');
  MultiByteToWideChar(CP_UTF8, 0, s.data(), (int)s.size(),
                      &ret[0], len);
  return ret;
}


// Replace every "@" in `s` with `n`.
static std::string subst(std::string const &s, int n)
{
  std::string ret;
  for (char c : s) {
    if (c == '@') {
      ret += std::to_string(n);
    }
    else {
      ret += c;
    }
  }
  return ret;
}


// Python source lines, each a C++ line as a Python string literal.
// They have double quotes and backslashes so the argument quoting has
// something to do.  "@" becomes a counter.
static char const * const cppLineTemplates[] = {
  R"(  'static int f@(int x)',)",
  R"(  '{',)",
  R"(  '  printf("f@: x=%d\\n", x);',)",
  R"(  '  return x + @;',)",
  R"(  '}',)",
  R"(  '',)",
};


// Return the heredoc body, exactly `size` bytes, or "" if `size` is
// too small, in which case set `minSize`.
static std::string makeHeredocBody(int size, int &minSize)
{
  std::string header =
    "# bash-experiment heredoc, " + std::to_string(size) + " bytes.\n"
    "p='bash-experiment.out'\n"
    "lines=[\n"
    "  '// bash-experiment.out',\n"
    "  '#include <stdio.h>                      // printf',\n"
    "  '',\n";

  std::string footer =
    "]\n"
    "open(p,'w',newline='').write('\\n'.join(lines)+'\\n')\n"
    "s=open(p,newline='').read()\n"
    "reps=[\n"
    "  ('// bash-experiment.out',\n"
    "   '// bash-experiment.out: generated by bash-experiment.exe'),\n"
    "  ('return x + 1;', 'return x + 1;    // first'),\n"
    "]\n"
    "for old,new in reps:\n"
    "    assert s.count(old)<=1, (p, old)\n"
    "    s=s.replace(old,new)\n"
    "open(p,'w',newline='').write(s)\n"
    "print('bash-experiment ok', len(s))\n";

  // Final padding line: "  '//" + filler + "',\n".
  int const minPadLen = 8;

  minSize = (int)(header.size() + footer.size()) + minPadLen;
  if (size < minSize) {
    return "";
  }

  std::string body = header;
  int remaining = size - minSize + minPadLen;

  int const numTemplates =
    sizeof(cppLineTemplates) / sizeof(cppLineTemplates[0]);
  for (int i = 0; ; i++) {
    std::string line =
      subst(cppLineTemplates[i % numTemplates], i / numTemplates + 1)
      + "\n";
    if ((int)line.size() + minPadLen > remaining) {
      break;
    }
    body += line;
    remaining -= (int)line.size();
  }

  body += "  '//" + std::string(remaining - minPadLen, 'x') + "',\n";
  body += footer;
  return body;
}


// Quote `s` as a single-quoted bash word.
static std::string bashSingleQuote(std::string const &s)
{
  std::string ret = "'";
  for (char c : s) {
    if (c == '\'') {
      ret += "'\\''";
    }
    else {
      ret += c;
    }
  }
  ret += "'";
  return ret;
}


// Quote `arg` so that `CommandLineToArgvW` (and the MSVCRT) will
// decode it back to `arg`.  This is libuv's `quote_cmd_arg` algorithm,
// written forwards.
static std::wstring quoteArg(std::wstring const &arg)
{
  if (arg.empty()) {
    return L"\"\"";
  }
  if (arg.find_first_of(L" \t\"") == std::wstring::npos) {
    return arg;
  }
  if (arg.find_first_of(L"\"\\") == std::wstring::npos) {
    return L"\"" + arg + L"\"";
  }

  std::wstring ret = L"\"";
  size_t i = 0;
  while (true) {
    size_t numBackslashes = 0;
    while (i < arg.size() && arg[i] == L'\\') {
      i++;
      numBackslashes++;
    }

    if (i == arg.size()) {
      // Backslashes before the closing quote must be doubled.
      ret.append(numBackslashes * 2, L'\\');
      break;
    }
    else if (arg[i] == L'"') {
      // Double them, then escape the quote.
      ret.append(numBackslashes * 2 + 1, L'\\');
      ret.push_back(L'"');
    }
    else {
      // Backslashes not before a quote are literal.
      ret.append(numBackslashes, L'\\');
      ret.push_back(arg[i]);
    }
    i++;
  }
  ret.push_back(L'"');
  return ret;
}


// Return the `-c` argument: the Bash tool's wrapper around `command`.
static std::string wrapCommand(std::string const &command)
{
  char cwdFile[64];
  snprintf(cwdFile, sizeof(cwdFile), "/c/cygwin/tmp/claude-%04lx-cwd",
    (unsigned long)(GetCurrentProcessId() & 0xFFFF));

  return
    "export TEMP='C:\\cygwin\\tmp' TMP='C:\\cygwin\\tmp' && "
    "{ [ -n \"${TMPDIR:-}\" ] || export TMPDIR=/c/cygwin/tmp; } && "
    "\\builtin shopt -u extglob 2>/dev/null || true && "
    "{ \\builtin unalias -- 'which'; \\builtin unset -f -- 'which'; } "
      ">/dev/null 2>&1 || true && "
    "{ \\builtin unalias -- 'unsetenv'; "
      "\\builtin unset -f -- 'unsetenv'; } >/dev/null 2>&1 || true && "
    "eval " + bashSingleQuote(command) + " < /dev/null && "
    "pwd -P >| " + cwdFile;
}


// Create a pipe whose `childEnd` is inheritable and `parentEnd` is
// not.  If `childReads`, the child gets the read end.
static void makePipe(bool childReads, HANDLE &childEnd,
                     HANDLE &parentEnd)
{
  SECURITY_ATTRIBUTES sa = {};
  sa.nLength = sizeof(sa);
  sa.bInheritHandle = TRUE;

  HANDLE readEnd, writeEnd;
  if (!CreatePipe(&readEnd, &writeEnd, &sa, 0)) {
    failWin32("CreatePipe");
  }
  childEnd = childReads? readEnd : writeEnd;
  parentEnd = childReads? writeEnd : readEnd;
  if (!SetHandleInformation(parentEnd, HANDLE_FLAG_INHERIT, 0)) {
    failWin32("SetHandleInformation");
  }
}


// Copy everything from `src` to `dest` until EOF.
static void relay(HANDLE src, FILE *dest)
{
  char buf[4096];
  DWORD n;
  while (ReadFile(src, buf, sizeof(buf), &n, nullptr) && n > 0) {
    fwrite(buf, 1, n, dest);
    fflush(dest);
  }
}


int main(int argc, char **argv)
{
  if (argc != 3) {
    fprintf(stderr, "usage: %s <bash> <size>\n", argv[0]);
    return EXIT_ERROR;
  }

  std::string bash = argv[1];
  char *end;
  long sizeL = strtol(argv[2], &end, 10);
  if (*argv[2] == '\0' || *end != '\0' || sizeL < 0 ||
      sizeL > 10000000) {
    fprintf(stderr, "bash-experiment: invalid size: %s\n", argv[2]);
    return EXIT_ERROR;
  }
  int size = (int)sizeL;

  int minSize;
  std::string body = makeHeredocBody(size, minSize);
  if (body.empty()) {
    fprintf(stderr, "bash-experiment: size %d is too small; "
      "the minimum is %d\n", size, minSize);
    return EXIT_ERROR;
  }

  std::string command = "true python3 - <<'EOF'\n" + body + "EOF";
  std::wstring cmdLine =
    quoteArg(toWide(bash)) + L" " +
    quoteArg(L"-c") + L" " +
    quoteArg(L"-l") + L" " +
    quoteArg(toWide(wrapCommand(command)));

  printf("bash-experiment: heredoc %d B, command %d B, "
    "command line %d chars\n",
    (int)body.size(), (int)command.size(), (int)cmdLine.size());
  fflush(stdout);

  // Pipes for the child's stdin, stdout, and stderr.
  HANDLE childStdin, parentStdin;
  HANDLE childStdout, parentStdout;
  HANDLE childStderr, parentStderr;
  makePipe(true, childStdin, parentStdin);
  makePipe(false, childStdout, parentStdout);
  makePipe(false, childStderr, parentStderr);

  // The CRT stdio table that libuv passes in `lpReserved2`: an int
  // count, then a flag byte per fd, then a HANDLE per fd, unaligned.
  int const numFds = 3;
  unsigned char const FOPEN = 0x01;
  unsigned char const FPIPE = 0x08;
  HANDLE fdHandles[numFds] = { childStdin, childStdout, childStderr };
  std::vector<BYTE> crtTable(
    sizeof(int) + numFds * (1 + sizeof(HANDLE)));
  memcpy(&crtTable[0], &numFds, sizeof(int));
  for (int i = 0; i < numFds; i++) {
    crtTable[sizeof(int) + i] = FOPEN | FPIPE;
    memcpy(&crtTable[sizeof(int) + numFds + i * sizeof(HANDLE)],
           &fdHandles[i], sizeof(HANDLE));
  }

  STARTUPINFOW si = {};
  si.cb = sizeof(si);
  si.dwFlags = STARTF_USESTDHANDLES | STARTF_USESHOWWINDOW;
  si.wShowWindow = SW_SHOWDEFAULT;
  si.cbReserved2 = (WORD)crtTable.size();
  si.lpReserved2 = &crtTable[0];
  si.hStdInput = childStdin;
  si.hStdOutput = childStdout;
  si.hStdError = childStderr;

  // Like libuv, put the child in a job that kills it when we exit.
  HANDLE job = CreateJobObjectW(nullptr, nullptr);
  if (!job) {
    failWin32("CreateJobObjectW");
  }
  JOBOBJECT_EXTENDED_LIMIT_INFORMATION jobInfo = {};
  jobInfo.BasicLimitInformation.LimitFlags =
    JOB_OBJECT_LIMIT_BREAKAWAY_OK |
    JOB_OBJECT_LIMIT_SILENT_BREAKAWAY_OK |
    JOB_OBJECT_LIMIT_DIE_ON_UNHANDLED_EXCEPTION |
    JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
  if (!SetInformationJobObject(job, JobObjectExtendedLimitInformation,
                               &jobInfo, sizeof(jobInfo))) {
    failWin32("SetInformationJobObject");
  }

  // Without this, Cygwin's /etc/profile does `cd $HOME` in a login
  // shell.  The Bash tool's shells keep their directory, so claude.exe
  // presumably sets it too (the profile unsets it, so it can't be
  // seen from inside).
  //
  // smcpeak: When I run `claude.exe`, I do so using a script that sets
  // CHERE_INVOKING=1.  That's because, as noted, without it, each time
  // Claude would run a program, the initial working directory would be
  // outside my project directory, which caused various problems.
  // (Claude always worked around them automatically, but this reduced
  // the friction a little.)
  //
  if (!SetEnvironmentVariableW(L"CHERE_INVOKING", L"1")) {
    failWin32("SetEnvironmentVariableW");
  }

  PROCESS_INFORMATION pi = {};
  if (!CreateProcessW(
        nullptr,                       // lpApplicationName
        &cmdLine[0],                   // lpCommandLine
        nullptr,                       // lpProcessAttributes
        nullptr,                       // lpThreadAttributes
        TRUE,                          // bInheritHandles
        CREATE_UNICODE_ENVIRONMENT,    // dwCreationFlags
        nullptr,                       // lpEnvironment
        nullptr,                       // lpCurrentDirectory
        &si,                           // lpStartupInfo
        &pi)) {                        // lpProcessInformation
    failWin32("CreateProcessW");
  }

  // libuv does this after creation too, and tolerates failure.
  if (!AssignProcessToJobObject(job, pi.hProcess)) {
    fprintf(stderr, "bash-experiment: note: "
      "AssignProcessToJobObject failed: code %lu\n",
      (unsigned long)GetLastError());
  }

  // Close our copies of the child's ends, and the child's stdin so
  // it sees EOF.
  CloseHandle(childStdin);
  CloseHandle(childStdout);
  CloseHandle(childStderr);
  CloseHandle(parentStdin);

  std::thread outThread(relay, parentStdout, stdout);
  std::thread errThread(relay, parentStderr, stderr);

  if (WaitForSingleObject(pi.hProcess, INFINITE) != WAIT_OBJECT_0) {
    failWin32("WaitForSingleObject");
  }
  outThread.join();
  errThread.join();

  DWORD exitCode;
  if (!GetExitCodeProcess(pi.hProcess, &exitCode)) {
    failWin32("GetExitCodeProcess");
  }
  printf("bash-experiment: bash exit code %lu\n",
    (unsigned long)exitCode);

  CloseHandle(pi.hThread);
  CloseHandle(pi.hProcess);
  CloseHandle(parentStdout);
  CloseHandle(parentStderr);
  CloseHandle(job);

  return exitCode == 0? EXIT_BASH_OK : EXIT_BASH_FAILED;
}


